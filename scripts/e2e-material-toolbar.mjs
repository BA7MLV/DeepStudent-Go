import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
const base = process.env.BASE_URL || 'http://localhost:5173';
const byId = (id) => page.getByTestId(id);
try {
  await page.goto(`${base}/#/library`);
  await page.locator('input[type=file]').setInputFiles({ name: '工具栏测试.md', mimeType: 'text/markdown', buffer: Buffer.from('# 批注测试\n\n' + '拖选文字进行高亮，工具栏默认收起。\n\n'.repeat(60)) });
  const item = page.locator('[data-testid="video-item"]').filter({ hasText: '工具栏测试' });
  await item.waitFor();
  const id = await item.getAttribute('data-video-id');
  await page.goto(`${base}/#/player/${id}`);
  await byId('ink-toggle').waitFor();
  assert.equal(await byId('ink-toggle').getAttribute('aria-expanded'), 'false');
  assert.equal(await byId('ink-pen').isVisible(), false);
  await byId('ink-toggle').click();
  await page.waitForFunction(() => document.querySelector('[data-testid="ink-pen"]')?.disabled === false);
  assert.equal(await byId('ink-pan').getAttribute('aria-checked'), 'true', '默认拖动');
  const scroll = page.locator('.mr-scroll');
  const bounds = await scroll.boundingBox();
  const x = bounds.x + bounds.width / 2, y = bounds.y + Math.min(bounds.height - 30, 280);
  await page.mouse.move(x, y);
  await page.mouse.down();
  assert.equal(await scroll.evaluate((el) => getComputedStyle(el).cursor), 'grabbing');
  await page.mouse.move(x, y - 150, { steps: 10 });
  await page.mouse.up();
  assert.ok(await scroll.evaluate((el) => el.scrollTop) > 100, '鼠标拖动实际滚动正文');
  assert.equal(await scroll.evaluate((el) => el.hasAttribute('data-dragging')), false, '抬手结束拖动');
  assert.equal(await page.evaluate(() => getSelection()?.toString() || ''), '', '拖动不选字');
  assert.equal(await page.locator('.ink-layer[data-active]').count(), 0, '拖动不进入书写');
  for (const tool of ['pen', 'highlight', 'erase', 'text-highlight']) {
    await byId(`ink-${tool}`).click();
    const cursor = await page.locator('.ink-layer[data-active]').first().evaluate((el) => getComputedStyle(el).cursor);
    if (tool === 'text-highlight') assert.equal(cursor, 'text');
    else assert.ok(cursor.startsWith('url('), `${tool} 使用独立工具光标`);
  }
  await byId('ink-pen').click();
  assert.equal(await page.getByLabel('笔型', { exact: true }).count(), 0, '高级设置默认收起');
  await byId('ink-more').click();
  await page.getByLabel('笔型', { exact: true }).selectOption('brush');
  await page.getByLabel('笔迹粗细').fill('5');
  await page.keyboard.press('Escape');
  await page.getByLabel('笔型', { exact: true }).waitFor({ state: 'detached' });
  assert.equal(await page.getByLabel('笔型', { exact: true }).count(), 0, 'Escape 收起更多选项');
  await byId('ink-toggle').click();
  assert.equal(await byId('ink-text-highlight').isVisible(), false);
  assert.equal(await byId('ink-pan').getAttribute('aria-checked'), 'true', '收起后恢复拖动，不残留隐藏工具');
  await byId('ink-toggle').click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await byId('ink-pen').isVisible(), true);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '窄屏无横向溢出');
  await byId('ink-pen').click();
  await byId('ink-more').click();
  const options = await page.getByRole('dialog', { name: '更多批注选项' }).boundingBox();
  assert.ok(options.x >= 0 && options.x + options.width <= 390, '窄屏更多面板不越界');
  await page.keyboard.press('Escape');
  await page.reload();
  await byId('ink-toggle').waitFor();
  assert.equal(await byId('ink-toggle').getAttribute('aria-expanded'), 'false', '刷新默认收起');
  await byId('ink-toggle').click();
  assert.equal(await byId('ink-pan').getAttribute('aria-checked'), 'true', '刷新默认拖动');

  await page.setViewportSize({ width: 1100, height: 900 });
  await page.goto(`${base}/#/library`);
  await page.locator('input[type=file]').setInputFiles('scripts/fixtures/sample-zh.pdf');
  const pdf = page.locator('[data-testid="video-item"]').filter({ hasText: 'sample-zh' });
  await pdf.waitFor();
  await page.goto(`${base}/#/player/${await pdf.getAttribute('data-video-id')}`);
  await byId('reader-tool-areaselect').waitFor();
  assert.equal(await byId('reader-tool-areaselect').evaluate((el) => el.previousElementSibling?.dataset.testid), 'ink-toggle', '框选紧邻批注工具');
  await byId('reader-tool-areaselect').click();
  await byId('reader-area-hint').waitFor();
  await byId('ink-toggle').click();
  await byId('ink-pan').click();
  assert.equal(await byId('reader-area-hint').count(), 0, '拖动与框选互斥');
  await byId('reader-tool-areaselect').click();
  await byId('reader-tool-areaselect').click();
  assert.equal(await byId('ink-pan').getAttribute('aria-checked'), 'true', '取消框选返回拖动');
  const canvas = page.locator('[data-page="1"] canvas');
  await canvas.waitFor();
  await canvas.evaluate((el) => el.scrollIntoView({ block: 'start', behavior: 'instant' }));
  const rect = await canvas.boundingBox();
  await byId('reader-tool-areaselect').click();
  const cropY = (await canvas.boundingBox()).y + 70;
  await page.mouse.move(rect.x + 60, cropY);
  await page.mouse.down();
  await page.mouse.move(rect.x + 210, cropY + 60, { steps: 10 });
  await page.mouse.up();
  await byId('ask-float').waitFor();
  assert.equal(await byId('ink-pan').getAttribute('aria-checked'), 'true', '框选完成返回拖动');
  assert.equal(await byId('reader-area-hint').count(), 0);
  await byId('ask-close').click();
  await byId('ink-highlight').click();
  const inkRect = await canvas.boundingBox();
  await page.mouse.move(inkRect.x + 70, inkRect.y + 80);
  await page.mouse.down();
  await page.mouse.move(inkRect.x + 170, inkRect.y + 80, { steps: 8 });
  await page.mouse.up();
  await page.locator('[data-ink-stroke]').waitFor();
  assert.equal(await byId('ink-pan').getAttribute('aria-checked'), 'true', '荧光笔一笔后返回拖动');
  await byId('reader-tool-areaselect').click();
  await byId('ink-toggle').click();
  assert.equal(await byId('reader-area-hint').count(), 0, '收起工具也退出框选');
  console.log('✓ 默认拖动、实际滚动、工具光标、更多设置、框选布局与互斥、窄屏和刷新通过');
} finally {
  await browser.close();
}
