import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Readable } from 'node:stream';
import { DatabaseStore } from '../apps/api/src/storage/database.ts';
import { CloudRecords } from '../apps/api/src/cloud/records.ts';
import { receiveFile } from '../apps/api/src/cloud/files.ts';
import { executorFor } from '../apps/api/src/cloud/execution.ts';
import { PluginService } from '../apps/api/src/plugins/service.ts';
import { reconcilePracticeExtractions } from '../apps/api/src/plugins/practice-extraction.ts';
import { reconcileLearningResults } from '../apps/api/src/plugins/learning-results.ts';

const root = path.join(os.tmpdir(), 'opencode'); fs.mkdirSync(root, { recursive: true });
const directory = fs.mkdtempSync(path.join(root, 'plugin-extraction-')), filesDir = path.join(directory, 'files'); fs.mkdirSync(filesDir);
const store = new DatabaseStore(path.join(directory, 'db.sqlite'), path.join(directory, 'system'));
const owner = crypto.randomUUID(), other = crypto.randomUUID();
for (const id of [owner, other]) store.db.prepare('INSERT INTO users(id,name,created_at) VALUES(?,?,?)').run(id, id, new Date().toISOString());
const records = new CloudRecords(store);
let service = new PluginService(store, undefined, undefined, { filesDir });
const put = (table, key, after) => records.apply(owner, [{ id: crypto.randomUUID(), table, key, before: records.get(owner, table, key), after }]);
const invoke = (args, user = owner) => service.invokeNamed(user, 'practice', 'extract-a', 1, 'extract', args);
const args = { materialId: 'a', clientNonce: 'extract-1' };
const results = () => service.invoke(owner, 'practice', 'extract-a', 1, 'learning.results', { materialId: 'a' }).tasks;
try {
  put('videos', 'a', { id: 'a', name: '资料 A', kind: 'material', materialFormat: 'md' });
  put('videos', 'b', { id: 'b', name: '资料 B', kind: 'material', materialFormat: 'pdf' });
  const doc = service.files.layout(owner), layout = JSON.parse(doc.content);
  layout.instances.push({ id: 'extract-a', pluginId: 'practice', scope: { kind: 'material', id: 'a' } });
  service.files.save(owner, doc.path, JSON.stringify(layout), doc.content, doc.revision);
  assert.throws(() => invoke({ ...args, materialId: 'b' }), /denied/);
  assert.throws(() => invoke(args, other), /not_found/);
  assert.throws(() => invoke({ ...args, text: 'injected prompt' }), /invalid_plugin_arguments/);
  const task = invoke(args);
  assert.equal(task.kind, 'qa'); assert.equal(task.executor, 'node');
  assert.equal(executorFor(task, records.get(owner, 'videos', 'a')), 'node');
  assert.equal(executorFor({ ...task, input: { ...task.input, pluginExtraction: false } }, null), 'node');
  assert.equal(invoke(args).id, task.id);
  assert.equal(records.get(owner, 'chatSessions', task.input.sessionId).videoId, 'a');
  assert.throws(() => invoke({ ...args, clientNonce: 'duplicate' }), /generation_conflict/);
  const bankId = '__course_questions__a';
  const text = '# 用户笔记必须保留\n\n```quiz\n' + JSON.stringify({ questions: [{ stem: '原题', options: ['甲', '乙'], answer: 0, explanation: '原文解析。', answerSource: 'original', source: { courseId: 'a', name: '资料 A', page: 1 } }] }) + '\n```\n';
  const bytes = Buffer.from(text), file = await receiveFile(store, filesDir, owner, Readable.from([bytes]), 'questions.md', 'text/markdown', bytes.length, bytes.length);
  put('videos', bankId, { id: bankId, name: '题库', kind: 'material', materialFormat: 'md' });
  put('files', bankId, { id: bankId, blob: { $file: file.id } });
  store.db.prepare("UPDATE cloud_tasks SET status='completed',result=? WHERE id=?").run(JSON.stringify({ content: '模型自称保存成功' }), task.id);
  reconcilePracticeExtractions(service); reconcileLearningResults(store);
  assert.equal(results()[0].artifacts, null, 'prose or an unrelated changed bank is not a save receipt');
  assert.match(results()[0].deliveryError, /save_unconfirmed/);
  // A durable server tool checkpoint is restored before result projection.
  store.db.prepare('UPDATE cloud_tasks SET progress=? WHERE id=?').run(JSON.stringify({ questionBankSaved: true }), task.id);
  await service.close(); service = new PluginService(store, undefined, undefined, { filesDir });
  const receipt = results()[0];
  assert.ok(receipt.artifacts, JSON.stringify(receipt));
  assert.equal(receipt.artifacts.kind, 'question-bank'); assert.equal(receipt.artifacts.count, 1);
  assert.equal(receipt.artifacts.path, '/courses/a/questions.md'); assert.ok(receipt.deliveredAt);
  reconcilePracticeExtractions(service); reconcileLearningResults(store);
  assert.equal(store.db.prepare('SELECT COUNT(*) AS n FROM plugin_learning_receipts WHERE task_id=?').get(task.id).n, 1);
  const second = invoke({ ...args, clientNonce: 'extract-2' });
  assert.equal(second.input.bankRevision, receipt.artifacts.revision);
  store.db.prepare("UPDATE cloud_tasks SET status='completed',progress=? WHERE id=?").run(JSON.stringify({ questionBankSaved: true }), second.id);
  reconcilePracticeExtractions(service); reconcileLearningResults(store);
  assert.match(results().find(t => t.id === second.id).deliveryError, /no_new_bank/);
  assert.equal(records.get(owner, 'files', bankId).blob.$file, file.id, 'projection never rewrites the authoritative bank');
  console.log('Practice extraction passed: server QA routing, host-owned session, schema/owner/material/nonce guards, generation exclusion, real Markdown receipt, no prose-only success, restart replay and idempotency, existing-bank CAS baseline.');
} finally { await service.close(); store.close(); fs.rmSync(directory, { recursive: true, force: true }); }
