import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { DatabaseStore } from '../apps/api/src/storage/database.ts';
import { CloudRecords } from '../apps/api/src/cloud/records.ts';
import { RecordProjections } from '../apps/api/src/realtime/record-projections.ts';

const directory = fs.mkdtempSync('/private/var/folders/2r/zv45t_9d6ljfqfj6l1r0yvtr0000gn/T/opencode/session-index-');
let store = new DatabaseStore(path.join(directory, 'db.sqlite'), path.join(directory, 'system'));
const owner = 'index-owner', other = 'index-other', videoId = '__library_assistant__';
const request = { kind: 'sessionIndex', videoId, archived: false, recentOnly: false };
const write = (table, key, after, who = owner) => {
  const records = new CloudRecords(store);
  return records.apply(who, [{ id: crypto.randomUUID(), table, key, before: records.get(who, table, key), after }]);
};
const read = (options = {}, who = owner) => new RecordProjections(store).sessionIndex(who, { ...request, ...options });
try {
  for (const id of [owner, other]) store.db.prepare('INSERT INTO users(id,name,created_at) VALUES(?,?,?)').run(id, id, new Date().toISOString());
  for (let id = 1; id <= 120; id++) write('chatSessions', id, { id, videoId, title: `Session ${id}`, createdAt: id, pinned: id === 1 });
  const first = read(), second = read({ cursor: first.next }), third = read({ cursor: second.next });
  assert.deepEqual(first.sessions.map(row => row.id), [1, ...Array.from({ length: 49 }, (_, i) => 120 - i)]);
  assert.equal(new Set([...first.sessions, ...second.sessions, ...third.sessions].map(row => row.id)).size, 120);
  assert.equal(third.next, undefined);
  assert.deepEqual(read({ cursor: third.previous }), second, 'reverse keyset page restores the exact preceding page');
  assert.deepEqual(read({ cursor: second.previous }), first);
  assert.equal(read({}, other).sessions.length, 0);
  assert.throws(() => read({ cursor: first.next }, other), /projection_cursor_scope/);
  assert.throws(() => read({ cursor: first.next, archived: true }), /projection_cursor_scope/);
  assert.throws(() => new RecordProjections(store).page(owner, { kind: 'collectionPage', table: 'chatSessions', cursor: first.next }), /projection_cursor_scope/);
  assert.equal(read({ recentOnly: true }).sessions.length, 0);
  let message = { id: 1, sessionId: 2, videoId, role: 'user', content: 'original', createdAt: 200 };
  const versionBefore = read().version;
  const firstReceipt = write('chats', 1, message);
  assert.ok(read().version > versionBefore);
  assert.equal(read({ recentOnly: true }).sessions[0].id, 2);
  assert.throws(() => read({ cursor: first.next }), /projection_cursor_expired/);
  const stable = read(), beforeStream = store.db.prepare("SELECT COALESCE(MAX(revision),0) AS n FROM client_changes WHERE domain='session_index'").get().n;
  message = { ...message, content: 'streamed new text' };
  const secondReceipt = write('chats', 1, message);
  assert.ok(secondReceipt.versions[0].revision > firstReceipt.versions[0].revision, 'UPSERT preserves monotonic record revision');
  assert.equal(read().version, stable.version, 'content-only write does not invalidate navigation');
  assert.equal(store.db.prepare("SELECT COALESCE(MAX(revision),0) AS n FROM client_changes WHERE domain='session_index'").get().n, beforeStream);
  assert.equal(read({ cursor: stable.next }).sessions.length, 50);
  write('chatSessions', 501, { id: 501, videoId: 'unrelated-course', title: 'Other course', createdAt: 501 });
  assert.equal(read().version, stable.version, 'unrelated course navigation leaves this cursor valid');
  assert.equal(read({ cursor: stable.next }).sessions.length, 50);
  write('chats', 1, { ...message, sessionId: 3 });
  assert.deepEqual(read({ recentOnly: true }).sessions.map(row => row.id), [3]);
  write('chats', 2, { ...message, id: 2, sessionId: 3, role: 'assistant', createdAt: 300 });
  assert.equal(read({ recentOnly: true }).sessions[0].activity, 300);
  write('chats', 2, null);
  assert.equal(read({ recentOnly: true }).sessions[0].activity, 200);
  write('chats', 1, null);
  assert.equal(read({ recentOnly: true }).sessions.length, 0);
  const beforeRollback = read();
  assert.throws(() => store.transaction(() => { write('chatSessions', 120, null); throw new Error('injected'); }), /injected/);
  assert.deepEqual(read(), beforeRollback);
  const oldCourseVersion = read().version;
  const otherCourseVersion = read({ videoId: 'unrelated-course' }).version;
  write('chatSessions', 120, { id: 120, videoId: 'unrelated-course', title: 'Moved session', createdAt: 120 });
  assert.ok(read().version > oldCourseVersion);
  assert.ok(read({ videoId: 'unrelated-course' }).version > otherCourseVersion);
  assert.equal(read().sessions.some(row => row.id === 120), false);
  const plan = store.db.prepare(`EXPLAIN QUERY PLAN SELECT id FROM client_session_index WHERE owner_id=? AND video_id=? AND archived=0 AND has_user=1
    ORDER BY pinned DESC,activity DESC,created_at DESC,id DESC LIMIT 51`).all(owner, videoId);
  assert.ok(plan.some(row => row.detail.includes('client_session_index_recent')));
  assert.ok(plan.every(row => !/SCAN |TEMP B-TREE/.test(row.detail)));
  store.transaction(() => {
    for (let id = 1; id <= 60; id++) write('chats', 1000 + id, { id: 1000 + id, sessionId: id, videoId, role: 'user', content: 'activity fixture', createdAt: id });
    write('chatSessions', 777, { id: 777, videoId, title: 'Newest created, no messages', createdAt: 999999 });
  });
  assert.equal(read().latestId, 777, 'landing selection remains newest-created even outside activity page');
  assert.ok(!read().sessions.some(row => row.id === 777));
  const landingPlan = store.db.prepare(`EXPLAIN QUERY PLAN SELECT id FROM client_session_index WHERE owner_id=? AND video_id=? AND archived=0 ORDER BY created_at DESC,id DESC LIMIT 1`).all(owner, videoId);
  assert.ok(landingPlan.some(row => row.detail.includes('client_session_index_created')));
  assert.ok(landingPlan.every(row => !/SCAN |TEMP B-TREE/.test(row.detail)));
  const persisted = read(); store.close();
  store = new DatabaseStore(path.join(directory, 'db.sqlite'), path.join(directory, 'system'));
  assert.deepEqual(read(), persisted, 'reopen never rebuilds a valid derived index');
  assert.equal(read({ cursor: persisted.next }).sessions.length, 50);
  fs.writeFileSync(path.join(directory, 'evidence.json'), JSON.stringify({ passed: true, plan, checks: ['50-row keyset pages, stable ties and pins', 'account/filter/cross-domain cursor isolation', 'user presence, activity, move/delete/tombstones', 'monotonic UPSERT revisions and zero content-only nav invalidation', 'transaction rollback and persistent reopen'] }, null, 2));
  console.log(`PASS lightweight session index: ${directory}`);
} finally { store.close(); }
