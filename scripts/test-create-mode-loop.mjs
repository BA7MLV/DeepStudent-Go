import assert from 'node:assert/strict';
import { CallLedger } from '../apps/web/src/harness/loopGuard.ts';
const ledger = new CallLedger();
const read = JSON.stringify({ operation: 'list' }), layout = JSON.stringify({ operation: 'layout' });
assert.equal(ledger.record('plugins', read), false); assert.equal(ledger.record('plugins', read), true);
ledger.recordResult('edit', '已创建 /system/plugins/new/views/main.html', '{"path":"/system/plugins/new/views/main.html"}');
assert.equal(ledger.record('plugins', read), false, 'actual asset writes permit rediscovery');
ledger.recordResult('edit', 'Error: denied', '{"path":"/system/plugins/new/manifest.json"}');
assert.equal(ledger.record('plugins', read), true, 'failed edit does not permit redundant discovery');
assert.equal(ledger.record('plugins', layout), false);
const mutation = '{"operation":"configure","content":"{}","expected":"{}","revision":1}';
assert.equal(ledger.record('plugins', mutation), false);
ledger.recordResult('plugins', 'Error: system_revision_conflict', mutation);
assert.equal(ledger.record('plugins', layout), false, 'CAS conflict permits fresh layout read');
assert.equal(ledger.record('plugins', mutation), true, 'exact failed write remains guarded');
ledger.recordResult('plugins', '{"path":"/system/plugin-layout.json","revision":2}', mutation);
assert.equal(ledger.record('plugins', layout), false, 'successful CAS permits verification');
assert.equal(ledger.record('plugins', mutation), true, 'successful write is not repeated');
assert.equal(ledger.record('read', '{"path":"/system/memory/preferences.md"}'), false);
ledger.recordResult('plugins', '{}', '{"operation":"lifecycle"}');
assert.equal(ledger.record('read', '{"path":"/system/memory/preferences.md"}'), true, 'unrelated read fingerprints survive');
console.log('Create mode loop guard passed: reread after real package/layout mutations and CAS conflict, no repeated writes or failed-edit bypass.');
