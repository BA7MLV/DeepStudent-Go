import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Readable } from 'node:stream';
import sharp from 'sharp';
import { DatabaseStore } from '../apps/api/src/storage/database.ts';
import { CloudRecords } from '../apps/api/src/cloud/records.ts';
import { receiveFile } from '../apps/api/src/cloud/files.ts';
import { ensureImageReference, attachmentFileInUse } from '../apps/api/src/cloud/attachment-images.ts';
import { migrateChatAttachmentReferences, migrateTerminalTaskAttachmentReferences } from '../apps/api/src/cloud/attachment-migration.ts';
import { normalizeChatAttachments, resolveAttachmentMessages } from '../apps/api/runtime/chat-attachments.ts';
import { attachmentMessage } from '../packages/study-core/src/chat/attachments.ts';

const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'opencode/attachment-references-'));
const filesDir = path.join(directory, 'files'); fs.mkdirSync(filesDir);
const store = new DatabaseStore(path.join(directory, 'db.sqlite'));
const records = new CloudRecords(store);
const owner = crypto.randomUUID(), other = crypto.randomUUID();
for (const id of [owner, other]) store.db.prepare('INSERT INTO users(id,name,created_at) VALUES(?,?,?)').run(id, id, new Date().toISOString());
const put = (id, after) => records.apply(owner, [{ id: crypto.randomUUID(), table: 'chats', key: id, before: records.get(owner, 'chats', id), after }]);
try {
  const bytes = await sharp({ create: { width: 1200, height: 800, channels: 3, background: '#345678' } }).png().toBuffer();
  const file = await receiveFile(store, filesDir, owner, Readable.from(bytes), 'original.png', 'image/png', 1_000_000);
  const metadata = await ensureImageReference(store, filesDir, owner, file.id);
  assert.deepEqual(await ensureImageReference(store, filesDir, owner, file.id), metadata);
  assert.equal(metadata.width, 1200); assert.equal(metadata.height, 800);
  assert.notEqual(metadata.previewServerId, file.id);
  const preview = store.db.prepare('SELECT * FROM files WHERE id=?').get(metadata.previewServerId);
  assert.equal(preview.owner_id, owner); assert.equal(preview.mime_type, 'image/webp');
  const previewMetadata = await sharp(path.join(filesDir, preview.storage_name)).metadata();
  assert.equal(previewMetadata.width, 640); assert.ok(previewMetadata.height <= 640);
  const draft = { id: 'attachment', serverId: file.id, name: 'spoof', mimeType: 'wrong', size: 1, dataUrl: 'data:image/png;base64,draft', previewServerId: 'foreign' };
  const attachments = normalizeChatAttachments(store, owner, [draft]);
  assert.equal(attachments[0].dataUrl, undefined);
  assert.equal(attachments[0].previewServerId, metadata.previewServerId);
  assert.equal(attachments[0].name, 'original.png');
  assert.throws(() => normalizeChatAttachments(store, other, [draft]), /无权/);
  const messages = [attachmentMessage({ role: 'user', content: 'read this', attachments })];
  assert.ok(JSON.stringify(messages).includes(`attachment-file:${file.id}`));
  const context = { store, owner, filesDir, checkActive() {} };
  const resolved = resolveAttachmentMessages(context, messages);
  assert.equal(resolved[0].content[1].image_url.url, `data:image/png;base64,${bytes.toString('base64')}`);
  assert.ok(!JSON.stringify(messages).includes('base64'));
  assert.throws(() => resolveAttachmentMessages({ ...context, owner: other }, messages), /unavailable/);
  assert.equal(attachmentFileInUse(store, owner, file.id), false);
  put(1, { id: 1, role: 'user', content: 'preserve', attachments });
  assert.equal(attachmentFileInUse(store, owner, file.id), true);
  assert.equal(attachmentFileInUse(store, owner, metadata.previewServerId), true);
  assert.equal(attachmentFileInUse(store, other, file.id), false);
  const dataUrl = `data:image/png;base64,${bytes.toString('base64')}`;
  put(2, { id: 2, role: 'user', content: 'legacy', attachments: [{ ...draft, dataUrl }], modelTrace: { source: 'legacy', messages: [{ role: 'user', content: [{ type: 'image_url', image_url: { url: dataUrl } }] }] } });
  put(3, { id: 3, role: 'user', content: 'invalid remains', attachments: [{ id: 'bad', dataUrl: 'data:image/png;base64,invalid' }] });
  const invalid = records.get(owner, 'chats', 3);
  const first = await migrateChatAttachmentReferences(store, records, filesDir, owner);
  assert.deepEqual({ ...first, nextRevision: 0 }, { migrated: 1, failed: 1, raced: 0, nextRevision: 0 });
  assert.ok(first.nextRevision > 0);
  const migrated = records.get(owner, 'chats', 2);
  assert.equal(migrated.attachments[0].serverId, file.id, 'must preserve original rather than replace with legacy thumbnail');
  assert.ok(!JSON.stringify(migrated).includes('data:image/'));
  assert.equal(migrated.content, 'legacy');
  assert.deepEqual(records.get(owner, 'chats', 3), invalid);
  assert.deepEqual(await migrateChatAttachmentReferences(store, records, filesDir, owner), { migrated: 0, failed: 1, raced: 0, nextRevision: first.nextRevision });
  const count = store.db.prepare('SELECT count(*) n FROM files').get().n;
  await migrateChatAttachmentReferences(store, records, filesDir, owner);
  assert.equal(store.db.prepare('SELECT count(*) n FROM files').get().n, count);
  put(4, { id: 4, role: 'user', content: 'race', attachments: [{ ...draft, dataUrl }] });
  const transaction = store.transaction.bind(store);
  let injectRace = true;
  store.transaction = fn => {
    if (injectRace) { injectRace = false; put(4, { ...records.get(owner, 'chats', 4), content: 'concurrent edit' }); }
    return transaction(fn);
  };
  const raced = await migrateChatAttachmentReferences(store, records, filesDir, owner, 20, first.nextRevision);
  store.transaction = transaction;
  assert.equal(raced.raced, 1);
  assert.equal(records.get(owner, 'chats', 4).content, 'concurrent edit');
  assert.equal(records.get(owner, 'chats', 4).attachments[0].dataUrl, dataUrl);
  const taskId = crypto.randomUUID(), activeId = crypto.randomUUID(), now = new Date().toISOString();
  const input = JSON.stringify({ attachments: [{ ...draft, dataUrl }] });
  for (const [id, status] of [[taskId, 'completed'], [activeId, 'running']]) store.db.prepare('INSERT INTO cloud_tasks(id,owner_id,nonce,kind,resource,input,status,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?,?)').run(id, owner, id, 'chat', 'session:1', input, status, now, now);
  const tasks = await migrateTerminalTaskAttachmentReferences(store, filesDir, owner);
  assert.equal(tasks.migrated, 1);
  assert.ok(!store.db.prepare('SELECT input FROM cloud_tasks WHERE id=?').get(taskId).input.includes('data:image/'));
  assert.equal(store.db.prepare('SELECT input FROM cloud_tasks WHERE id=?').get(activeId).input, input);
  assert.equal((await migrateTerminalTaskAttachmentReferences(store, filesDir, owner)).migrated, 0);
  const blockedOwner = crypto.randomUUID();
  store.db.prepare('INSERT INTO users(id,name,created_at) VALUES(?,?,?)').run(blockedOwner, blockedOwner, now);
  for (let id = 1; id <= 21; id++) records.apply(blockedOwner, [{ id: crypto.randomUUID(), table: 'chats', key: id, before: null,
    after: { id, role: 'user', content: 'bounded migration', attachments: [{ id: `legacy-${id}`, dataUrl: id <= 20 ? 'data:image/png;base64,invalid' : dataUrl }] } }]);
  const blocked = await migrateChatAttachmentReferences(store, records, filesDir, blockedOwner, 20);
  assert.equal(blocked.failed, 20); assert.equal(blocked.migrated, 0);
  const continuation = await migrateChatAttachmentReferences(store, records, filesDir, blockedOwner, 20, blocked.nextRevision);
  assert.equal(continuation.migrated, 1); assert.equal(continuation.failed, 0);
  assert.ok(records.get(blockedOwner, 'chats', 21).attachments[0].serverId);
  assert.equal(records.get(blockedOwner, 'chats', 1).attachments[0].dataUrl, 'data:image/png;base64,invalid');
  const source = store.db.prepare('SELECT storage_name FROM files WHERE id=?').get(file.id);
  fs.writeFileSync(path.join(filesDir, source.storage_name), Buffer.from('corrupt'));
  assert.throws(() => resolveAttachmentMessages(context, messages), /corrupt/);
  console.log('PASS attachment references: original/preview, bounds, ownership, normalization, original model bytes, revocation, trace migration, retry/idempotency, failure preservation, corruption');
} finally { store.close(); fs.rmSync(directory, { recursive: true, force: true }); }
