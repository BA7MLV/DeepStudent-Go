test('A -> B -> A and same-account rebuild use terminal identities, not account strings', async () => {
  const lifecycle = createAccountLifecycle();
  const a = lifecycle.acquire('A');
  assert.equal(lifecycle.acquire('A'), a);
  let released = 0;
  a.own(() => { released++; assert.equal(a.current(), false); });
  const b = lifecycle.acquire('B');
  const nextA = lifecycle.acquire('A');
  assert.notEqual(nextA, a);
  assert.equal(a.signal.aborted, true);
  assert.equal(b.signal.aborted, true);
  assert.equal(released, 1);
  lifecycle.invalidate();
  const rebuiltA = lifecycle.acquire('A');
  assert.notEqual(rebuiltA, nextA);
  assert.throws(() => nextA.assertCurrent(), /client_account_changed/);
  assert.equal(rebuiltA.current(), true);
  lifecycle.invalidate();
  await lifecycle.settled();
});

test('late async acquisition releases on the original lifetime; cleanup can be detached', async () => {
  const lifecycle = createAccountLifecycle();
  const original = lifecycle.acquire('A');
  let resolve;
  const pending = new Promise(done => { resolve = done; });
  let releases = 0, detached = 0;
  const detach = original.own(() => { detached++; });
  detach();
  const acquiring = pending.then(() => {
    original.own(async () => { await Promise.resolve(); releases++; });
    original.assertCurrent();
  });
  lifecycle.invalidate();
  const next = lifecycle.acquire('A');
  resolve();
  await assert.rejects(acquiring, /client_account_changed/);
  await lifecycle.settled();
  assert.equal(releases, 1);
  assert.equal(detached, 0);
  assert.equal(next.current(), true);
  lifecycle.invalidate();
});

test('Cordis placement cleanup survives StrictMode setup/cleanup/setup and root invalidation', async () => {
  const lifecycle = createAccountLifecycle();
  const lifetime = lifecycle.acquire('A');
  const root = new Context();
  const scopes = createPluginScopes(root);
  const identity = { server: 'fixture', account: 'A', project: 'course', instance: 'one', placement: 'main', revision: 1 };
  let effects = 0;
  const first = scopes.acquire(identity, lifetime);
  first.own(() => { effects++; return () => { effects--; }; });
  first.release(); first.release();
  const second = scopes.acquire(identity, lifetime);
  second.own(() => { effects++; return () => { effects--; }; });
  await scopes.settled();
  assert.equal(first.current(), false);
  assert.equal(second.current(), true);
  assert.equal(effects, 1);
  lifecycle.invalidate();
  assert.equal(second.current(), false);
  assert.throws(() => second.assertCurrent(), /plugin_scope_expired/);
  await scopes.settled();
  assert.equal(effects, 0);
  const rebuilt = lifecycle.acquire('A');
  const third = scopes.acquire(identity, rebuilt);
  assert.notEqual(third.incarnation, second.incarnation);
  assert.equal(third.current(), true);
  lifecycle.invalidate();
  await scopes.settled();
  assert.equal(scopes.diagnostics().retains, 0);
  assert.equal(scopes.diagnostics().created, scopes.diagnostics().released);
  await root.fiber.dispose();
});

test('database replacement and versionchange invalidate account work without deleting journals or bytes', async t => {
  const owner = `account-lifecycle-${crypto.randomUUID()}`;
  storage.useCloudDatabase(owner);
  const originalDatabase = storage.db;
  t.after(async () => {
    accountLifecycle.invalidate(); storage.db.close();
    await Dexie.delete(storage.cloudDatabaseName(owner));
    setDatabaseNotice(null);
  });
  await originalDatabase.open();
  await originalDatabase.table('_cloudMeta').put({ id: 'draft', value: new Blob(['original draft bytes']) });
  await originalDatabase.table('_learningCommands').add({ operationId: 'original-intent', request: { edits: [] }, state: 'queued' });
  await originalDatabase.table('_historyTransactions').put({ id: 'original-history', rows: [{ id: 'original-operation' }] });
  const original = accountLifetime(owner);
  let released = 0;
  original.own(() => { released++; });
  storage.useCloudDatabase(owner);
  assert.equal(released, 1);
  assert.equal(original.current(), false);
  assert.notEqual(storage.db, originalDatabase);
  await storage.db.open();
  const rebuilt = accountLifetime(owner);
  assert.notEqual(rebuilt, original);
  assert.equal(await (await storage.db.table('_cloudMeta').get('draft')).value.text(), 'original draft bytes');
  assert.equal(await storage.db.table('_learningCommands').count(), 1);
  assert.equal(await storage.db.table('_historyTransactions').count(), 1);
  const upgrade = new Dexie(storage.db.name);
  upgrade.version(storage.db.verno + 1).stores({ _cloudMeta: 'id' });
  t.after(() => upgrade.close());
  await upgrade.open();
  assert.equal(rebuilt.current(), false);
  assert.equal(storage.db.isOpen(), false);
  await assert.rejects(storage.db.table('_cloudMeta').get('draft'), /DatabaseClosedError|closed/i);
  assert.equal(await (await upgrade.table('_cloudMeta').get('draft')).value.text(), 'original draft bytes');
  upgrade.close();
});
